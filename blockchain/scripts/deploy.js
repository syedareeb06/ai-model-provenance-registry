// Deploys ModelRegistry to the local Hardhat node and registers the demo
// consortium. Usage (two terminals):
//   npx hardhat node
//   npx hardhat run scripts/deploy.js --network localhost
const fs = require("fs");
const path = require("path");
const hre = require("hardhat");

const Role = { DataProvider: 1, Developer: 2, Auditor: 3 };

async function main() {
  const signers = await hre.ethers.getSigners();
  const [admin] = signers;

  const registry = await hre.ethers.deployContract("ModelRegistry", [], admin);
  await registry.waitForDeployment();
  const address = await registry.getAddress();
  console.log(`ModelRegistry deployed to ${address} by AI Safety Consortium ${admin.address}`);

  const consortium = [
    [signers[1], Role.DataProvider, "OpenHealth Data Lab"],
    [signers[2], Role.DataProvider, "AgriSense Open Data"],
    [signers[3], Role.Developer, "MedVision AI"],
    [signers[4], Role.Developer, "NeuralForge Studio"],
    [signers[5], Role.Auditor, "TrustAI Auditors"],
    [signers[6], Role.Auditor, "ClearBox Model Audits"],
  ];
  for (const [signer, role, name] of consortium) {
    await (await registry.registerMember(signer.address, role, name)).wait();
    console.log(`  registered ${name.padEnd(26)} ${signer.address}`);
  }

  const { chainId } = await hre.ethers.provider.getNetwork();
  const out = path.join(__dirname, "..", "..", "frontend", "js", "local-deployment.js");
  fs.writeFileSync(
    out,
    `// AUTO-GENERATED by blockchain/scripts/deploy.js\nwindow.LOCAL_DEPLOYMENT = ${JSON.stringify({ address, chainId: Number(chainId) })};\n`
  );
  console.log(`Wrote ${path.relative(process.cwd(), out)} - open the web app and choose "Local Hardhat".`);
}

main().catch((err) => {
  console.error(err);
  process.exitCode = 1;
});
